#   "Could not find app entry point: app.py".
#
# DATABRICKS APPS:
#   - Apps are containerized web apps hosted by Databricks
#   - The entry point must be named `app.py` and live at the root of
#     `source_code_path`
#   - Free Edition allows 3 apps per account, auto-stop after 24h
