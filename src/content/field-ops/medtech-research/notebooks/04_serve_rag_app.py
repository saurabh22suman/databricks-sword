# ────────────────────────────────────────────────────────────────────────────
# SECTION 1: Inspect the bundle yml to find the configured source_code_path
# ────────────────────────────────────────────────────────────────────────────
# The DAB yml was generated by bundle.ts. We read it to confirm the path.

import yaml
import os

# Find the bundle directory (created by `databricks bundle deploy` in deployment.ts)
bundle_path = f"/Workspace/Users/{spark.sql('SELECT current_user()').collect()[0][0]}/dbsword-fo-medtech-research"

try:
    with open(f"{bundle_path}/databricks.yml", "r") as f:
        bundle_yml = yaml.safe_load(f)
    configured_path = bundle_yml["resources"]["apps"]["medtech_rag_app"]["source_code_path"]
    print(f"📄 Configured source_code_path: {configured_path}")
except Exception as e:
    print(f"❌ Could not read bundle yml: {e}")
    raise

# COMMAND ----------

# ────────────────────────────────────────────────────────────────────────────
# SECTION 2: Verify app.py exists at the configured path
# ────────────────────────────────────────────────────────────────────────────
# Streamlit apps must have `app.py` at the root of source_code_path.
#
# ⚠️ BUG: If configured_path is './src/app.py', the file exists at
# $bundle_path/src/app.py — but the app runtime expects it at
# $bundle_path/app.py (the source_code_path itself is the root).

app_path = f"{bundle_path}/{configured_path.lstrip('./')}"
print(f"🔍 Looking for app.py at: {app_path}")

import os
if os.path.isfile(app_path):
    print(f"✅ Found app.py at {app_path}")
else:
    print(f"❌ app.py NOT found at {app_path}")
    print("   HINT: The source_code_path in databricks.yml is wrong.")
    print("         It should be './app' (a directory containing app.py at its root),")
    print("         NOT './src/app.py' (a path pointing directly to the file).")
    print()
    print("         Edit src/content/field-ops/medtech-research/bundle/databricks.yml")
    print("         and change `source_code_path: ./src/app.py` to `source_code_path: ./app`")
    print("         Then re-run the deploy command in your terminal:")
    print(f"           databricks bundle deploy --target dev --var catalog={catalog} --var schema_prefix={schema_prefix}")

# COMMAND ----------

# ────────────────────────────────────────────────────────────────────────────
# SECTION 3: Wait for the app to come online
# ────────────────────────────────────────────────────────────────────────────
# After fixing the yml and re-deploying, the app should be running within
# 1-2 minutes. We poll the apps API to confirm.

from databricks.sdk import WorkspaceClient
import time

w = WorkspaceClient()

print(f"⏳ Waiting for app '{app_name}' to come online (max 5 minutes)...")
for i in range(30):
    try:
        app = w.apps.get(name=app_name)
        state = getattr(app, "state", "UNKNOWN")
        url = getattr(app, "url", None)
        print(f"   [{i*10}s] state: {state}, url: {url}")
        if state == "RUNNING" and url:
            print(f"✅ App is running at {url}")
            break
    except Exception as e:
        print(f"   [{i*10}s] error: {e}")
    time.sleep(10)
else:
    print(f"❌ App never reached RUNNING state")
    print("   HINT: Re-check the source_code_path in databricks.yml and re-deploy.")

